def base(label):
    d=Document(); sec=d.sections[0]
    sec.page_width=Inches(8.5);sec.page_height=Inches(11)
    sec.top_margin=sec.bottom_margin=Inches(.65)
    sec.left_margin=sec.right_margin=Inches(.7)
    for name in ['Normal','Title','Heading 1','Heading 2']:
        st=d.styles[name];st.font.name='Arial';st.font.color.rgb=RGBColor(0,0,0)
        st.element.get_or_add_rPr().get_or_add_rFonts().set(qn('w:eastAsia'),'Microsoft YaHei')
        snap=OxmlElement('w:snapToGrid');snap.set(qn('w:val'),'0');st.element.get_or_add_pPr().append(snap)
    d.styles['Normal'].font.size=Pt(10.5)
    d.styles['Normal'].paragraph_format.space_after=Pt(4)
    d.styles['Normal'].paragraph_format.line_spacing=Pt(15)
    for name,size in [('Title',21),('Heading 1',15),('Heading 2',11.5)]:
        d.styles[name].font.size=Pt(size)
        d.styles[name].paragraph_format.space_before=Pt(8)
        d.styles[name].paragraph_format.space_after=Pt(4)
        d.styles[name].paragraph_format.line_spacing=1.0
    for node in list(d.styles.element.iter(qn('w:pBdr'))):node.getparent().remove(node)
    for node in list(d.settings.element.iter(qn('w:evenAndOddHeaders'))):node.getparent().remove(node)
    sec.different_first_page_header_footer=False
    h=sec.header.paragraphs[0];h.text='LULULEMON  /  D001  /  '+label
    h.style='Normal';h.runs[0].font.size=Pt(8);h.runs[0].font.color.rgb=RGBColor(70,70,70)
    f=sec.footer.paragraphs[0];f.text='2026-11-07  ·  v1.0                                      '
    fld=OxmlElement('w:fldSimple');fld.set(qn('w:instr'),'PAGE');f._p.append(fld)
    d.core_properties.title=label;d.core_properties.author='Lululemon MBA project team'
    return d

def p(d,s,style=None):return d.add_paragraph(s,style)
def heading(d,s):d.add_heading(s,1)
def sub(d,s):d.add_heading(s,2)
def page(d):d.add_page_break()
def table(d,headers,rows,widths=None):
    t=d.add_table(rows=1, cols=len(headers));t.style='Table Grid';t.autofit=False
    for c,h in zip(t.rows[0].cells,headers):
        c.text=h
        sh=OxmlElement('w:shd');sh.set(qn('w:fill'),'E8EEF1');c._tc.get_or_add_tcPr().append(sh)
        for run in c.paragraphs[0].runs:run.bold=True
    rep=OxmlElement('w:tblHeader');t.rows[0]._tr.get_or_add_trPr().append(rep)
    for row in rows:
        for c,txt in zip(t.add_row().cells,row):c.text=txt
    for row in t.rows:
        pr=row._tr.get_or_add_trPr();ns=OxmlElement('w:cantSplit');pr.append(ns)
        for j,c in enumerate(row.cells):
            if widths:c.width=Inches(widths[j])
            for par in c.paragraphs:
                par.paragraph_format.space_after=Pt(4)
                for run in par.runs:run.font.size=Pt(9.5)
    return t
def blank(d,label,lines=2):
    p(d,label)
    for _ in range(lines):p(d,'________________________________________________________________________')

